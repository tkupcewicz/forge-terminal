/// Returns `true` when no `forge.lua` exists yet and the wizard should run.
pub fn should_run_onboarding() -> bool {
    // Check FORGE_CONFIG_FILE env override first
    if let Ok(p) = std::env::var("FORGE_CONFIG_FILE") {
        if Path::new(&p).exists() {
            return false;
        }
    }
    // ~/.forge.lua
    let home = &*config::HOME_DIR;
    if home.join(".forge.lua").exists() {
        return false;
    }
    // ~/.config/forge/forge.lua (via xdg)
    let cfg_dir = config::forge_config_dir();
    if cfg_dir.join("forge.lua").exists() {
        return false;
    }
    true
}

/// Locate an existing WezTerm configuration file, if any.
pub fn find_wezterm_config() -> Option<PathBuf> {
    // WEZTERM_CONFIG_FILE env override
    if let Ok(p) = std::env::var("WEZTERM_CONFIG_FILE") {
        let path = PathBuf::from(&p);
        if path.exists() {
            return Some(path);
        }
    }
    let home = &*config::HOME_DIR;
    // ~/.wezterm.lua
    let p = home.join(".wezterm.lua");
    if p.exists() {
        return Some(p);
    }
    // ~/.config/wezterm/wezterm.lua
    let p = home.join(".config").join("wezterm").join("wezterm.lua");
    if p.exists() {
        return Some(p);
    }
    None
}

