/// Very simple heuristic: scan lines of a wezterm.lua for `config.KEY = VALUE`
/// patterns and return (key, wezterm_value, forge_default) triples for known
/// keys where Forge ships a different default.
fn detect_overrides(wezterm_path: &Path) -> Vec<(String, String, String)> {
    let forge_defaults: &[(&str, &str)] = &[
        ("color_scheme", "\"Forge Dark\""),
        ("enable_tab_bar", "false"),
        ("scrollback_lines", "50000"),
    ];

    let content = match fs::read_to_string(wezterm_path) {
        Ok(c) => c,
        Err(_) => return Vec::new(),
    };

    let mut overrides = Vec::new();
    for (key, forge_val) in forge_defaults {
        // Match lines like:  config.color_scheme = "Catppuccin"
        let needle = format!("config.{}", key);
        for line in content.lines() {
            let trimmed = line.trim();
            if let Some(rest) = trimmed.strip_prefix(&needle) {
                let rest = rest.trim();
                if let Some(rest) = rest.strip_prefix('=') {
                    let user_val = rest.trim().to_string();
                    if user_val != *forge_val {
                        overrides.push((key.to_string(), user_val, forge_val.to_string()));
                    }
                }
            }
        }
    }
    overrides
}

/// Helper to resolve a config key value from the user's override choices.
fn resolve_override_full(
    choices: &[(String, String, String, bool)],
    key: &str,
    forge_default: &str,
) -> String {
    // choices: (key, user_val, forge_val, keep_user)
    for (k, user_val, _forge_val, keep_user) in choices {
        if k == key {
            return if *keep_user {
                user_val.clone()
            } else {
                forge_default.to_string()
            };
        }
    }
    forge_default.to_string()
}

/// Write `forge.lua` using the full override choice data.
fn generate_forge_config_full(
    wezterm_config: &Option<PathBuf>,
    project_dir: &str,
    choices: &[(String, String, String, bool)], // (key, user_val, forge_val, keep_user)
) -> PathBuf {
    let cfg_dir = config::forge_config_dir();
    let _ = fs::create_dir_all(&cfg_dir);
    let dest = cfg_dir.join("forge.lua");

    let mut buf = String::new();
    buf.push_str("-- Forge Terminal Configuration\n");
    buf.push_str("-- Generated by Forge onboarding wizard\n\n");
    buf.push_str("local forge = require(\"forge\")\n");
    buf.push_str("local config = forge.config_builder()\n\n");

    // Theme
    buf.push_str("-- Theme\n");
    let color_scheme = resolve_override_full(choices, "color_scheme", "\"Forge Dark\"");
    buf.push_str(&format!("config.color_scheme = {}\n\n", color_scheme));

    // Side Panel
    buf.push_str("-- Side Panel\n");
    buf.push_str("config.enable_side_panel = true\n");
    let enable_tab_bar = resolve_override_full(choices, "enable_tab_bar", "false");
    buf.push_str(&format!("config.enable_tab_bar = {}\n\n", enable_tab_bar));

    // Claude Sessions
    buf.push_str("-- Claude Sessions\n");
    buf.push_str(&format!(
        "config.default_project_dir = \"{}\"\n",
        project_dir.replace('\\', "\\\\").replace('"', "\\\"")
    ));
    buf.push_str("config.claude_command = \"claude\"\n\n");

    // Scrollback
    buf.push_str("-- Scrollback\n");
    let scrollback = resolve_override_full(choices, "scrollback_lines", "50000");
    buf.push_str(&format!("config.scrollback_lines = {}\n\n", scrollback));

    // Import extra lines from wezterm config
    if let Some(wez_path) = wezterm_config {
        if let Ok(content) = fs::read_to_string(wez_path) {
            let known_keys: &[&str] = &[
                "color_scheme",
                "enable_tab_bar",
                "scrollback_lines",
                "enable_side_panel",
                "default_project_dir",
                "claude_command",
            ];
            let mut extras = Vec::new();
            for line in content.lines() {
                let trimmed = line.trim();
                if trimmed.starts_with("config.") {
                    if let Some(rest) = trimmed.strip_prefix("config.") {
                        let key = rest.split('=').next().unwrap_or("").trim();
                        if !known_keys.contains(&key) {
                            extras.push(trimmed.to_string());
                        }
                    }
                }
            }
            if !extras.is_empty() {
                buf.push_str("-- Imported from WezTerm config\n");
                for line in &extras {
                    buf.push_str(line);
                    buf.push('\n');
                }
                buf.push('\n');
            }
        }
    }

    buf.push_str("return config\n");
    let _ = fs::write(&dest, &buf);
    dest
}

